# Registered before the items router so /export isn't read as /{item_id}.
router = APIRouter(prefix="/store/items", tags=["Store"])

# Template and export share one column order (owner, 2026-11-07): the
# "Name at <unit>" columns sit right after item_name.
COLUMNS_BEFORE_UNITS = ["item_type", "category", "subcategory", "item_name"]
COLUMNS_AFTER_UNITS = ["uom", "technical_specification", "lead_time_days", "legacy_code", "part_code", "hsn_sac_code",
                       "gst_rate", "preferred_vendor", "standard_cost", "min_order_qty", "reorder_level"]


def file_columns(units) -> list[str]:
    return COLUMNS_BEFORE_UNITS + [_unit_col(u.name) for u in units] + COLUMNS_AFTER_UNITS


def _number(raw: str, label: str) -> float | None:
    """Blank → None; otherwise a number ≥ 0. Raises ValueError with the reason."""
    if not raw:
        return None
    try:
        value = float(str(raw).replace(",", "").replace("%", "").replace("₹", "").strip())
    except ValueError:
        raise ValueError(f"{label} '{raw}' isn't a number — enter digits only, e.g. 125.50.") from None
    if value < 0:
        raise ValueError(f"{label} can't be negative — got {value:g}.")
    return value


def _cell(r: dict, *names: str) -> str:
    """First non-blank of several header spellings (import template name, or
    the Excel export's column title)."""
    for n in names:
        if r.get(n):
            return r[n]
    return ""


def _spec(r: dict) -> str:
    """Technical specification cell; older files used a `description` column."""
    return r.get("technical_specification") or r.get("description") or ""
MAX_ROWS = 5000


def _key(header) -> str:
    """Header → snake key, so the Excel export's titles ("Item Name",
    "Lead Time (days)", "HSN / SAC", "Name at Unit 1") read the same as the
    template's names (item_name, lead_time_days …)."""
    import re
    k = re.sub(r"[^a-z0-9]+", "_", str(header or "").strip().lower()).strip("_")
    return {"hsn_sac": "hsn_sac_code", "gst": "gst_rate"}.get(k, k)


def _unit_col(unit_name: str) -> str:
    """Column title of a unit-wise name in the export / template."""
    return f"Name at {unit_name}"


def _read_rows(filename: str, raw: bytes) -> list[dict]:
    name = (filename or "").lower()
    if name.endswith((".xlsx", ".xlsm")):
        from openpyxl import load_workbook
        try:
            ws = load_workbook(io.BytesIO(raw), read_only=True, data_only=True).active
        except Exception:
            raise HTTPException(status_code=422, detail="Could not open the Excel file — save it as .xlsx (or CSV) and try again.")
        rows = list(ws.iter_rows(values_only=True))
        if not rows:
            return []
        headers = [_key(h) for h in rows[0]]
        return [{headers[i]: ("" if v is None else str(v).strip()) for i, v in enumerate(r) if i < len(headers)} for r in rows[1:]]
    if not name.endswith(".csv"):
        raise HTTPException(status_code=422, detail="Upload a .csv or .xlsx file — download the template to start from the right columns.")
    try:
        text = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        raise HTTPException(status_code=422, detail="Could not read the file as UTF-8 text — save it as CSV (UTF-8) from Excel and try again.")
    reader = csv.DictReader(io.StringIO(text))
    return [{_key(k): (v or "").strip() for k, v in r.items()} for r in reader]


def _type_value(raw: str, labels: dict[str, str]) -> str | None:
    """Accepts the code (tool_equipment) or the label (Tool & Equipment)."""
    if not raw:
        return "material"
    key = raw.strip().lower()
    for value, label in labels.items():
        if key in (value, label.lower(), label.lower().replace(" & ", " and ")):
            return value
    return None


@router.get("/import/template")
async def import_template(db: Session = Depends(get_db),
                          _user: User = Depends(require_tab_action("store", "items", "import"))):
    units = store_units(db)
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(file_columns(units))
    w.writerow(["Material", "Hardware & Fasteners", "", "Hex Bolt M12x50"] + [""] * len(units)
               + ["NOS", "Zinc plated", "21", "HWF-BLT-0012", "", "7318", "18", "", "12.50", "100", "200"])
    w.writerow(["Consumable", "PPE", "", "Safety Gloves"] + [""] * len(units)
               + ["PAIR", "", "", "", "", "", "", "", "", "", ""])
    return StreamingResponse(iter([buf.getvalue()]), media_type="text/csv",
                             headers={"Content-Disposition": 'attachment; filename="item_master_import_template.csv"'})


@router.post("/import")
async def import_items(
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
    user: User = Depends(require_tab_action("store", "items", "import")),
):
    # Role visibility: the file is not checked line by line against a restricted Item Type list.
    if visibility.allowed_values(user, "store:items", "item_type") is not None:
        raise HTTPException(
            status_code=422,
            detail="Your role limits the Item Type of new items, and the Excel import is not checked line by line — add them "
                   "from Add Item, or ask an admin to widen Item Type for your role "
                   "(Organization › Role & Permissions › Store › Item Master › Visibility).")
    rows = _read_rows(file.filename, await file.read())
    if not rows:
        raise HTTPException(status_code=422, detail="The file has no data rows — fill in at least one item under the header row.")
    if len(rows) > MAX_ROWS:
        raise HTTPException(status_code=422, detail=f"The file has {len(rows)} rows — import at most {MAX_ROWS} at a time by splitting it.")
    if "item_name" not in rows[0] or "uom" not in rows[0]:
        raise HTTPException(status_code=422, detail="Missing the item_name / uom columns — download the template and keep its header row.")

    uoms = {o["value"] for o in uom_options(db)}
    labels = {t.value: t.label for t in item_types(db)}
    # Same name with a different technical specification is a different item (e.g. a different spec).
    by_name = {(n.strip().lower(), (d or '').strip().lower()): (c, n)
               for c, n, d in db.query(StoreItem.item_code, StoreItem.item_name, StoreItem.description).all()}
    top_cats = db.query(StoreItemCategory).filter(StoreItemCategory.parent_id.is_(None)).all()
    gst_rates = [float(r) for (r,) in db.query(GSTRate.rate).filter(GSTRate.is_active.is_(True)).all()]
    vendors = db.query(Vendor.id, Vendor.code, Vendor.name).filter(Vendor.status == "active").all()
    # Unit-wise names: one "Name at <unit>" column per unit that runs a store.
    unit_cols = {_key(_unit_col(u.name)): u for u in store_units(db)}

    def unit_names_of(r: dict) -> list[dict]:
        out = []
        for col, unit in unit_cols.items():
            n = (r.get(col) or "").strip()
            if n:
                if len(n) > 200:
                    raise ValueError(f"The name at {unit.name} is longer than 200 characters — shorten it.")
                out.append({"branch_id": unit.id, "name": n})
        return out

    created, existing, errors = [], [], []
    new_units: list[str] = []
    new_categories: list[dict] = []
    seen_names: dict[str, int] = {}
    seen_legacy: dict[str, int] = {}

    for idx, r in enumerate(rows, start=2):  # row 1 is the header
        name = r.get("item_name", "")
        if not any(r.values()):
            continue
        if not name:
            errors.append({"row": idx, "item_name": "", "reason": "Item name is empty — fill in item_name."})
            continue

        # Already exists → don't save, report it.
        key = (name.lower(), _spec(r).lower())
        match = by_name.get(key)
        if match:
            # Export → fill the unit-wise names → import again: the names are saved on the existing item.
            reason = "Same name and technical specification already exist"
            try:
                names = unit_names_of(r)
            except ValueError as exc:
                errors.append({"row": idx, "item_name": name, "reason": str(exc)})
                continue
            if names:
                item = db.query(StoreItem).filter(StoreItem.item_code == match[0]).first()
                if item:
                    merged = {u["branch_id"]: u["name"] for u in (item.unit_names or [])}
                    merged.update({u["branch_id"]: u["name"] for u in names})
                    new = [{"branch_id": b, "name": n} for b, n in merged.items()]
                    if new != (item.unit_names or []):
                        item.unit_names = new
                        reason = "Already exists — unit-wise names updated"
            existing.append({"row": idx, "item_name": name, "existing_code": match[0], "existing_name": match[1],
                             "reason": reason})
            continue
        if key in seen_names:
            existing.append({"row": idx, "item_name": name, "existing_code": None, "existing_name": name,
                             "reason": f"Repeats row {seen_names[key]} of this file"})
            continue

        uom = r.get("uom", "").upper()
        if not uom:
            errors.append({"row": idx, "item_name": name, "reason": "UOM is empty — fill in a unit like NOS, KG or MTR."})
            continue
        if uom not in uoms:
            # New unit in the file → added to the unit master (label = code; rename it in Settings › Units of Measure).
            if len(uom) > 20:
                errors.append({"row": idx, "item_name": name, "reason": f"UOM '{uom}' is too long — a unit code is at most 20 characters (NOS, KG, MTR…)."})
                continue
            db.add(StoreUom(code=uom, label=uom))
            db.flush()
            uoms.add(uom)
            new_units.append(uom)
        item_type = _type_value(r.get("item_type", ""), labels)
        if not item_type:
            errors.append({"row": idx, "item_name": name, "reason": f"Item type '{r.get('item_type')}' isn't valid — use one of: {', '.join(labels.values())}."})
            continue

        category = subcategory = None
        if r.get("category"):
            cat_name = r["category"].strip()
            cat = next((c for c in top_cats if c.name.lower() == cat_name.lower() and c.item_type in (item_type, None)), None)
            if not cat:
                # New category in the file → created for this item type (ledgers can be set later in Settings › Categories).
                if len(cat_name) > 150:
                    errors.append({"row": idx, "item_name": name, "reason": f"Category '{cat_name[:40]}…' is too long — keep it to 150 characters."})
                    continue
                cat = StoreItemCategory(name=cat_name, code=_auto_code(db, cat_name), parent_id=None, item_type=item_type)
                db.add(cat)
                db.flush()
                top_cats.append(cat)
                new_categories.append({"category": cat.name, "subcategory": None, "item_type": labels[item_type]})
            category = cat.name
            if r.get("subcategory"):
                sub_name = r["subcategory"].strip()
                sub = db.query(StoreItemCategory).filter(
                    StoreItemCategory.parent_id == cat.id, func.lower(StoreItemCategory.name) == sub_name.lower()).first()
                if not sub:
                    if len(sub_name) > 150:
                        errors.append({"row": idx, "item_name": name, "reason": f"Subcategory '{sub_name[:40]}…' is too long — keep it to 150 characters."})
                        continue
                    sub = StoreItemCategory(name=sub_name, code=_auto_code(db, sub_name), parent_id=cat.id, item_type=item_type)
                    db.add(sub)
                    db.flush()
                    new_categories.append({"category": cat.name, "subcategory": sub.name, "item_type": labels[item_type]})
                subcategory = sub.name
        elif r.get("subcategory"):
            errors.append({"row": idx, "item_name": name, "reason": "Subcategory given without a category — fill in the category too."})
            continue

        try:
            lead_time = check_lead_time(_cell(r, "lead_time_days", "lead time (days)"))
            legacy = check_legacy_code(db, _cell(r, "legacy_code", "legacy code"))
            hsn = check_hsn_sac(_cell(r, "hsn_sac_code", "hsn / sac"), item_type)
            gst = _number(_cell(r, "gst_rate", "gst %"), "GST rate")
            if gst is not None and not any(abs(gst - g) < 0.001 for g in gst_rates):
                raise ValueError(f"GST {gst:g}% isn't an active Finance GST rate — use one of: {', '.join(f'{g:g}' for g in sorted(gst_rates)) or 'none set up yet'}.")
            vendor_id = None
            vendor_raw = _cell(r, "preferred_vendor", "preferred vendor").strip().lower()
            if vendor_raw:
                hits = [v for v in vendors if vendor_raw in ((v.code or "").lower(), (v.name or "").strip().lower())]
                if len(hits) != 1:
                    raise ValueError(f"Preferred vendor '{vendor_raw}' {'matches several vendors' if hits else 'is not an active vendor'} — use the vendor code from Procurement → Vendors.")
                vendor_id = hits[0].id
            std_cost = _number(_cell(r, "standard_cost", "standard cost"), "Standard cost")
            moq = _number(_cell(r, "min_order_qty", "min order qty"), "Minimum order quantity")
            reorder = _number(_cell(r, "reorder_level", "reorder level"), "Reorder level")
            names = unit_names_of(r)
        except ValueError as exc:
            errors.append({"row": idx, "item_name": name, "reason": str(exc)})
            continue
        if legacy and legacy.lower() in seen_legacy:
            errors.append({"row": idx, "item_name": name,
                           "reason": f"Legacy code '{legacy}' repeats row {seen_legacy[legacy.lower()]} of this file — each legacy code can belong to one item only."})
            continue

        item = StoreItem(
            item_code=generate_item_code(db),
            item_name=name, item_type=item_type, category=category, subcategory=subcategory,
            description=_spec(r) or None, uom=uom, lead_time_days=lead_time, legacy_code=legacy,
            part_number=_cell(r, "part_code", "part code").strip() or None, hsn_sac_code=hsn, gst_rate=gst,
            preferred_vendor_id=vendor_id, standard_cost=std_cost, min_order_qty=moq, reorder_level=reorder,
            unit_names=names or None,
        )
        db.add(item)
        db.flush()
        seen_names[key] = idx
        if legacy:
            seen_legacy[legacy.lower()] = idx
        created.append({"row": idx, "item_code": item.item_code, "item_name": name,
                        "item_type": labels[item_type], "category": category})

    db.commit()
    return {"created": created, "existing": existing, "errors": errors,
            "new_units": new_units, "new_categories": new_categories}


@router.get("/export")
async def export_items(
    item_type: str | None = Query(None),
    search: str | None = Query(None),
    category: str | None = Query(None),
    subcategory: str | None = Query(None),
    status: str | None = Query(None),
    db: Session = Depends(get_db),
    _user: User = Depends(require_tab_action("store", "items", "export")),
):
    """Excel of the Item Master with the same filters as the list page."""
    from app.modules.store.services.stock_values import sees_standard_cost
    show_cost = sees_standard_cost(_user)  # Store › Items › Stock value & rates
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill

    query = db.query(StoreItem)
    if item_type:
        query = query.filter(StoreItem.item_type == item_type)
    if category:
        query = query.filter(StoreItem.category == category)
    if subcategory:
        query = query.filter(StoreItem.subcategory == subcategory)
    if status:
        query = query.filter(StoreItem.status == status)
    from app.modules.store.routes.items import apply_item_search, item_search_order
    query = apply_item_search(query, search)
    items = query.order_by(*item_search_order(search)).all()
    labels = {t.value: t.label for t in item_types(db)}

    wb = Workbook()
    ws = wb.active
    ws.title = "Item Master"
    units = store_units(db)
    headers = file_columns(units)  # same columns as the import template, so the file imports back as is
    vendor_names = {v.id: v.code for v in db.query(Vendor.id, Vendor.code).all()}
    ws.append(headers)
    for cell in ws[1]:
        cell.font = Font(bold=True)
        cell.fill = PatternFill("solid", fgColor="FDF1E6")
    for i in items:
        ws.append([labels.get(i.item_type or "", i.item_type or ""), i.category or "", i.subcategory or "", i.item_name]
                  + [next((u["name"] for u in (i.unit_names or []) if u.get("branch_id") == unit.id), "") for unit in units]
                  + [i.uom, i.description or "",
                   i.lead_time_days if i.lead_time_days is not None else "", i.legacy_code or "",
                   i.part_number or "", i.hsn_sac_code or "", i.gst_rate if i.gst_rate is not None else "",
                   vendor_names.get(i.preferred_vendor_id, ""),
                   i.standard_cost if i.standard_cost is not None and show_cost else "",
                   i.min_order_qty if i.min_order_qty is not None else "",
                   i.reorder_level if i.reorder_level is not None else ""])
    from openpyxl.utils import get_column_letter
    for n, width in enumerate([18, 24, 20, 34] + [28] * len(units) + [8, 36, 16, 18, 16, 14, 10, 18, 14, 14, 14], start=1):
        ws.column_dimensions[get_column_letter(n)].width = width
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return StreamingResponse(buf, media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                             headers={"Content-Disposition": 'attachment; filename="item_master.xlsx"'})
