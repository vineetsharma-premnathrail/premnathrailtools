@router.post("/import")
async def import_service_requests(
    request: Request,
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
    user: User = Depends(require_app_access("erp")),
    _tab: User = Depends(require_tab_action("erp", "service_requests", "import")),
):
    # Importing raises new SRs, so it needs Create as well as Import.
    ensure_tab_action(user, "erp", "service_requests", "create")
    rows = read_rows(file.filename, await file.read())
    check_rows(rows, ["machine_serial_number", "issue_title", "service_type"])

    machines = {norm_key(p.serial_number): p for p in db.query(Project).all()}
    existing_srs = db.query(ServiceRequest).all()
    by_legacy = {norm_key(s.legacy_sr_number): s for s in existing_srs if s.legacy_sr_number}
    by_issue = {(s.project_id, norm_key(s.issue_title), _reported_on(s)): s for s in existing_srs}
    users = db.query(User).filter(User.is_active == True).all()  # noqa: E712
    users_by_email = {u.email.lower(): u for u in users if u.email}
    users_by_name: dict[str, list[User]] = {}
    for u in users:
        users_by_name.setdefault(norm_key(u.name), []).append(u)

    created, existing, errors = [], [], []
    seen_legacy: dict[str, int] = {}
    seen_issue: dict[tuple, int] = {}
    today = datetime.now(IST).date()

    for idx, r in enumerate(rows, start=2):  # row 1 is the header
        if not any(str(v).strip() for v in r.values()):
            continue
        serial = text(r, "machine_serial_number") or ""
        title = text(r, "issue_title") or ""
        key = f"{serial} — {title}" if serial or title else ""

        def err(reason: str):
            errors.append({"row": idx, "key": key, "reason": reason})

        if not serial:
            err("Machine Serial Number is empty — every SR must name the machine it is raised against.")
            continue
        if not title:
            err("Issue Title is empty — describe the problem in a short line.")
            continue
        machine = machines.get(norm_key(serial))
        if not machine:
            err(f"No machine with serial number {serial} — register it on the Projects tab (or import it there) first.")
            continue
        if machine.is_deleted:
            err(f"Machine {machine.serial_number} is in the Recycle Bin — restore it before importing SRs against it.")
            continue

        try:
            reported = parse_date(r, "reported_date", "Reported Date") or today
        except ValueError as exc:
            err(str(exc))
            continue
        legacy = text(r, "old_sr_number")

        # Duplicate → not saved, reported next to the SR it matched.
        lkey = norm_key(legacy) if legacy else None
        if lkey and lkey in by_legacy:
            existing.append({"row": idx, "key": key, "existing_ref": by_legacy[lkey].request_number,
                             "existing_label": _sr_label(by_legacy[lkey]), "reason": f"Old SR number {legacy} was already imported"})
            continue
        if lkey and lkey in seen_legacy:
            existing.append({"row": idx, "key": key, "existing_ref": None, "existing_label": legacy,
                             "reason": f"Old SR number repeats row {seen_legacy[lkey]} of this file"})
            continue
        ikey = (machine.id, norm_key(title), reported)
        if ikey in by_issue:
            m = by_issue[ikey]
            existing.append({"row": idx, "key": key, "existing_ref": m.request_number, "existing_label": _sr_label(m),
                             "reason": f"Same machine, issue title and reported date ({reported.strftime('%d-%m-%Y')}) already exist"})
            continue
        if ikey in seen_issue:
            existing.append({"row": idx, "key": key, "existing_ref": None, "existing_label": title,
                             "reason": f"Same machine, issue title and reported date as row {seen_issue[ikey]} of this file"})
            continue

        try:
            service_type = parse_choice(r, "service_type", "Service Type", SERVICE_TYPE_CHOICES)
            if not service_type:
                raise ValueError(f"Service Type is empty — use one of: {', '.join(SERVICE_TYPE_CHOICES.values())}.")
            priority = parse_choice(r, "priority", "Priority", PRIORITY_CHOICES, default="standard")
            status = parse_choice(r, "status", "Status", STATUS_CHOICES, default="open")
            payment_status = parse_choice(r, "payment_status", "Payment Status", PAYMENT_CHOICES)
            dates = {k: parse_date(r, k, LABELS[k]) for k in (
                "expected_date_to_attend", "expected_completion_date", "actual_date_attended",
                "actual_completion_date", "closed_date", "customer_sign_off_date")}
            numbers = {k: parse_number(r, k, LABELS[k]) for k in (
                "actual_service_duration_hours", "downtime_hours", "service_cost", "transport_cost",
                "accommodation_cost", "miscellaneous_cost")}
            tax = parse_number(r, "tax_percentage", "Tax Percentage", maximum=100)
            satisfaction = parse_number(r, "customer_satisfaction", "Customer Satisfaction", minimum=1, maximum=5)
        except ValueError as exc:
            err(str(exc))
            continue

        corrective = text(r, "corrective_action")
        if status == "closed" and not corrective:
            err("Status is Closed but Corrective Action is empty — fill in what was done to fix it (same rule as closing an SR on screen).")
            continue
        for k in ("actual_date_attended", "actual_completion_date", "closed_date"):
            if dates[k] and dates[k] < reported:
                err(f"{LABELS[k]} {dates[k].strftime('%d-%m-%Y')} is before the Reported Date {reported.strftime('%d-%m-%Y')} — check both dates.")
                break
        else:
            if dates["actual_date_attended"] and dates["actual_completion_date"] and dates["actual_completion_date"] < dates["actual_date_attended"]:
                err("Actual Completion Date is before Actual Date Attended — the job can't finish before it starts.")
                continue
            assignee = None
            assigned_raw = text(r, "assigned_to")
            if assigned_raw:
                assignee = users_by_email.get(assigned_raw.lower())
                if not assignee:
                    named = users_by_name.get(norm_key(assigned_raw), [])
                    if len(named) == 1:
                        assignee = named[0]
                    elif len(named) > 1:
                        err(f"Assigned To '{assigned_raw}' matches {len(named)} users — write the person's email instead.")
                        continue
                    else:
                        err(f"Assigned To '{assigned_raw}' isn't an active portal user — write their portal email, or leave it blank.")
                        continue

            try:
                base = ServiceRequestCreate(
                    project_id=machine.id, issue_title=title, issue_description=text(r, "issue_description"),
                    issue_category=text(r, "issue_category"), sub_category=text(r, "sub_category"),
                    failure_mode=text(r, "failure_mode"), priority=priority, service_type=service_type,
                    assigned_service_person_id=assignee.id if assignee else None,
                    assigned_to_name=assignee.name if assignee else None,
                    expected_date_to_attend=dates["expected_date_to_attend"],
                    expected_completion_date=dates["expected_completion_date"],
                    reported_by_name=text(r, "reported_by_name"), reported_by_phone=text(r, "reported_by_phone"),
                    reported_by_email=text(r, "reported_by_email"), service_report_notes=text(r, "service_report_notes"),
                )
            except ValidationError as exc:
                err(validation_reason(exc, LABELS))
                continue

            sr = ServiceRequest(
                request_number=_generate_sr_number(db), legacy_sr_number=legacy, created_by_id=user.id,
                opened_at=_at_ist_noon(reported), **base.model_dump(exclude={"status"}),
                status=status,
                actual_date_attended=dates["actual_date_attended"], actual_completion_date=dates["actual_completion_date"],
                actual_service_duration_hours=numbers["actual_service_duration_hours"], downtime_hours=numbers["downtime_hours"],
                root_cause=text(r, "root_cause"), resolution_description=corrective,
                preventive_actions=text(r, "preventive_actions"),
                customer_feedback=text(r, "customer_feedback"),
                customer_satisfaction=int(satisfaction) if satisfaction is not None else None,
                customer_sign_off_name=text(r, "customer_sign_off_name"), customer_sign_off_date=dates["customer_sign_off_date"],
                service_cost=numbers["service_cost"] or 0, transport_cost=numbers["transport_cost"] or 0,
                accommodation_cost=numbers["accommodation_cost"] or 0, miscellaneous_cost=numbers["miscellaneous_cost"] or 0,
                tax_percentage=18.0 if tax is None else tax,
                payment_status=payment_status, invoice_number=text(r, "invoice_number"),
                created_notification_sent=True, closed_notification_sent=True,
            )
            if status == "closed":
                closed_on = dates["closed_date"] or dates["actual_completion_date"] or reported
                sr.closed_at = _at_ist_noon(closed_on)
            db.add(sr)
            db.flush()
            _recompute_billing(db, sr)
            _write_audit(db, sr.id, "created", user, request,
                         summary=f"Service request {sr.request_number} imported from {file.filename} by {user.name or user.email}"
                                 + (f" (old number {legacy})." if legacy else "."))
            if lkey:
                seen_legacy[lkey] = idx
            seen_issue[ikey] = idx
            created.append({"row": idx, "id": sr.id, "ref": sr.request_number, "name": title,
                            "detail": f"{machine.serial_number} · {STATUS_CHOICES[status]}"})

    if created:
        notify_user(
            db, user_id=user.id, title="Service Request Import Finished",
            message=f"{len(created)} service request(s) imported from {file.filename}; {len(existing)} already existed and {len(errors)} had problems (not saved).",
            notification_type="erp_import_result", entity_type="service_request",
        )
    db.commit()
    return {"created": created, "existing": existing, "errors": errors}


@router.get("/export")
async def export_service_requests(
    search: str | None = Query(None),
    status: str | None = Query(None),
    priority: str | None = Query(None),
    service_type: str | None = Query(None),
    project_id: int | None = Query(None),
    ids: str | None = Query(None, description="Comma-separated SR ids — export only these (other filters ignored)."),
    date_field: str = Query("reported"),
    date_from: date | None = Query(None),
    date_to: date | None = Query(None),
    db: Session = Depends(get_db),
    _user: User = Depends(require_app_access("erp")),
    _tab: User = Depends(require_tab_action("erp", "service_requests", "export")),
):
    """Excel of the SR registry with the same filters as the list page. SR
    Number and the billing totals come first; the remaining columns match the
    import template, so the sheet can be re-imported (duplicates are skipped).

    `ids` exports exactly the ticked SRs. Otherwise the list filters apply,
    plus an optional From–To range on the reported or closed date (both
    ends inclusive, days in IST)."""
    selected = parse_export_ids(ids, "service requests")
    if date_field not in EXPORT_DATE_FIELDS:
        raise HTTPException(status_code=422, detail=f"Unknown date '{date_field}' — choose one of: {', '.join(EXPORT_DATE_FIELDS.values())}.")
    check_date_range(date_from, date_to)
    query = db.query(ServiceRequest, Project).join(Project, ServiceRequest.project_id == Project.id).filter(
        ServiceRequest.is_deleted == False)  # noqa: E712
    query = apply_scope(query, _user, ServiceRequest)
    if selected is not None:
        results = query.filter(ServiceRequest.id.in_(selected)).order_by(ServiceRequest.created_at.desc()).all()
        if not results:
            raise HTTPException(status_code=404, detail="None of the selected service requests exist any more — they may have been deleted. Refresh the list.")
        return _srs_xlsx(results)
    if search:
        like = f"%{search}%"
        query = query.filter(
            ServiceRequest.request_number.ilike(like) | ServiceRequest.issue_title.ilike(like)
            | ServiceRequest.issue_description.ilike(like) | ServiceRequest.issue_category.ilike(like)
            | Project.serial_number.ilike(like) | Project.client_name.ilike(like)
        )
    if status:
        query = query.filter(ServiceRequest.status == status)
    if priority:
        query = query.filter(ServiceRequest.priority == priority)
    if service_type:
        query = query.filter(ServiceRequest.service_type == service_type)
    if project_id:
        query = query.filter(ServiceRequest.project_id == project_id)
    results = query.order_by(ServiceRequest.created_at.desc()).all()
    if date_from or date_to:
        pick = _reported_on if date_field == "reported" else (lambda sr: ist_date(sr.closed_at))
        results = [(sr, p) for sr, p in results if in_range(pick(sr), date_from, date_to)]
    return _srs_xlsx(results)


# Which SR date a From–To export filters on.
EXPORT_DATE_FIELDS = {"reported": "Reported date", "closed": "Closed date"}


def _srs_xlsx(results: list):
    def closed_on(sr: ServiceRequest):
        if not sr.closed_at:
            return ""
        ts = sr.closed_at if sr.closed_at.tzinfo else sr.closed_at.replace(tzinfo=timezone.utc)
        return ts.astimezone(IST).date()

    def row(sr: ServiceRequest, p: Project) -> list:
        values = {
            "machine_serial_number": p.serial_number, "old_sr_number": sr.legacy_sr_number,
            "service_type": SERVICE_TYPE_CHOICES.get(sr.service_type or "", sr.service_type),
            "priority": PRIORITY_CHOICES.get(sr.priority or "", sr.priority),
            "status": STATUS_CHOICES.get(sr.status or "", sr.status),
            "payment_status": PAYMENT_CHOICES.get(sr.payment_status or "", sr.payment_status),
            "reported_date": _reported_on(sr) or "", "closed_date": closed_on(sr),
            "assigned_to": sr.assigned_to_name, "corrective_action": sr.resolution_description,
        }
        out = [sr.request_number]
        for k, _ in COLUMNS:
            v = values[k] if k in values else getattr(sr, k, None)
            out.append("" if v is None else v)
        return out + [sr.total_material_cost or 0, sr.tax_amount or 0, sr.total_bill or 0]

    headers = ["SR Number"] + [t for _, t in COLUMNS] + ["Material Cost", "Tax Amount", "Total Bill"]
    return xlsx_response("Service Requests", headers, [row(sr, p) for sr, p in results], "service_requests.xlsx")
