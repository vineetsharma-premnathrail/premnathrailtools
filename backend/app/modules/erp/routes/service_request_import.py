    ("issue_title", "Issue Title"), ("issue_description", "Issue Description"),
    ("service_type", "Service Type"), ("priority", "Priority"), ("status", "Status"),
    ("issue_category", "Issue Category"), ("sub_category", "Sub Category"), ("failure_mode", "Failure Mode"),
    ("reported_date", "Reported Date"), ("reported_by_name", "Reported By Name"),
    ("reported_by_phone", "Reported By Phone"), ("reported_by_email", "Reported By Email"),
    ("assigned_to", "Assigned To"),
    ("expected_date_to_attend", "Expected Date to Attend"), ("expected_completion_date", "Expected Completion Date"),
    ("actual_date_attended", "Actual Date Attended"), ("actual_completion_date", "Actual Completion Date"),
    ("closed_date", "Closed Date"),
    ("actual_service_duration_hours", "Actual Service Duration Hours"), ("downtime_hours", "Downtime Hours"),
    ("root_cause", "Root Cause"), ("corrective_action", "Corrective Action"),
    ("preventive_actions", "Preventive Actions"), ("service_report_notes", "Service Report Notes"),
    ("customer_feedback", "Customer Feedback"), ("customer_satisfaction", "Customer Satisfaction"),
    ("customer_sign_off_name", "Customer Sign Off Name"), ("customer_sign_off_date", "Customer Sign Off Date"),
    ("service_cost", "Service Cost"), ("transport_cost", "Transport Cost"),
