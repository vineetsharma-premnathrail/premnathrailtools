"""Bulk import / Excel export for Service Requests.

One template serves both jobs: raising new SRs in bulk (status Open, issue +
machine + service type) and bringing in old SRs from the previous system
(closed, with attended/completion dates, corrective action and costs).

Duplicate rule (2026-10-07): a row is the same SR when
  * its old_sr_number was already imported, or
  * the same machine already has an SR with the same issue title reported on
    the same date (live or in the Recycle Bin), or
  * it repeats an earlier row of the same file by either rule.
Duplicates are NOT saved; they come back in `existing` with the SR they
matched. SR numbers are always generated by the app (current FY series).

Imported SRs send no per-SR bell broadcast and no client/team emails — both
email idempotency flags are set so a later status change can't fire a
"created" mail for an old record. The importer gets one summary notice."""
