"""Quotation → editable Word document workflow (generate → edit in Word).

SharePoint/Graph is replaced by an in-memory fake so the tests exercise the
portal's own rules: one draft per revision, regenerate keeps history, the
latest Word version becomes what "Download PDF" serves, stale drafts can't
be edited or uploaded to, and only the creator/admin may change it.
"""

import io

import pytest
from docx import Document

from app.auth.jwt_handler import create_access_token
from app.core.config import settings
from app.modules.crm.models.inquiry import Inquiry
from app.modules.crm.models.organization import Organization
from app.modules.main.models.user import User
from app.modules.main.services import managed_documents


class FakeSharePoint:
    def __init__(self):
        self.files: dict[str, list[bytes]] = {}
        self.grants: list[tuple[str, str]] = []

    async def upload(self, site, folder, filename, content_type, data):
        item_id = f"item-{len(self.files) + 1}"
        self.files[item_id] = [data]
        return {"name": filename, "path": f"{folder}/{filename}", "webUrl": f"https://sp/{item_id}", "size": len(data), "item_id": item_id}

    async def replace(self, site, item_id, data, content_type):
        self.files[item_id].append(data)
        return {"id": item_id}

    async def grant(self, site, item_id, email):
        self.grants.append((item_id, email))

    async def versions(self, site, item_id):
        n = len(self.files[item_id])
        return [{"version": f"{i}.0", "modified_at": None, "modified_by": "System", "size": 1} for i in range(n, 0, -1)]

    async def version(self, site, item_id, version_id):
        return self.files[item_id][int(float(version_id)) - 1]

    async def download(self, site, item_id, as_pdf=False):
        return b"%PDF-from-word" if as_pdf else self.files[item_id][-1]


@pytest.fixture
def sp(monkeypatch):
    fake = FakeSharePoint()
    monkeypatch.setattr(settings, "SHAREPOINT_SITE_ID", "site-1")
    monkeypatch.setattr(managed_documents, "upload_bytes_to_sharepoint", fake.upload)
    monkeypatch.setattr(managed_documents, "replace_item_content", fake.replace)
    monkeypatch.setattr(managed_documents, "grant_item_edit_access", fake.grant)
    monkeypatch.setattr(managed_documents, "list_item_versions", fake.versions)
    monkeypatch.setattr(managed_documents, "download_item", fake.download)
    monkeypatch.setattr(managed_documents, "download_item_version", fake.version)
    return fake


def _user(db, email, role="user"):
    user = User(email=email, name=email.split("@")[0], role=role, is_active=True, assigned_apps=["crm"])
    db.add(user)
    db.commit()
    db.refresh(user)
    return user


def _auth(user):
    return {"Authorization": f"Bearer {create_access_token({'sub': str(user.id), 'email': user.email, 'role': user.role})}"}


def _quotation(client, db, owner):
    org = Organization(name="Delhi Metro Rail Corporation Ltd", address="Metro Bhawan", city="New Delhi")
    db.add(org)
    db.flush()
    inquiry = Inquiry(universal_id="PRT-INQ-2026-0042", org_id=org.id, created_by_id=owner.id)
    db.add(inquiry)
    db.commit()
    resp = client.post(f"/api/v1/crm/inquiries/{inquiry.id}/quotations", json={
        "client_name": org.name, "payment_terms": "1. 30% advance. 2. Balance before dispatch.",
        "items": [{"description": "Rail cum road vehicle", "model_number": "RRV-4", "quantity": 1, "unit_price": 4850000, "gst_percent": 18}],
    }, headers=_auth(owner))
    assert resp.status_code == 201, resp.text
    return inquiry.id, resp.json()


def test_generate_edit_upload_lifecycle(client, db, sp):
    owner = _user(db, "quot_owner@premnathrail.com")
    inquiry_id, quot = _quotation(client, db, owner)
    base = f"/api/v1/crm/inquiries/{inquiry_id}/quotations/{quot['id']}"
    dbase = f"/api/v1/managed-documents/crm_quotation/{quot['id']}"

    assert client.get(f"{dbase}", headers=_auth(owner)).json() == {"document": None}

    created = client.post(f"{dbase}", headers=_auth(owner))
    assert created.status_code == 200, created.text
    doc = created.json()["document"]
    assert doc["is_stale"] is False
    assert doc["versions"][0]["action"] == "Generated by system"
    assert doc["versions"][0]["modified_by"] == "quot_owner"
    # The generated .docx carries the real quotation content.
    text = "\n".join(p.text for p in Document(io.BytesIO(sp.files["item-1"][0])).paragraphs)
    assert "QUOTATION" in text and "30% advance" in text

    # A second plain "create" must not silently wipe edits.
    assert client.post(f"{dbase}", headers=_auth(owner)).status_code == 409
    regenerated = client.post(f"{dbase}?regenerate=true", headers=_auth(owner)).json()["document"]
    assert [v["action"] for v in regenerated["versions"]] == ["Rebuilt from system data", "Generated by system"]

    edit = client.post(f"{dbase}/edit", headers=_auth(owner))
    assert edit.status_code == 200 and edit.json()["url"] == "https://sp/item-1"
    client.post(f"{dbase}/edit", headers=_auth(owner))
    assert sp.grants == [("item-1", "quot_owner@premnathrail.com")]  # granted once per person

    bad = client.post(f"{dbase}/upload", files={"file": ("q.pdf", b"%PDF", "application/pdf")}, headers=_auth(owner))
    assert bad.status_code == 400
    docx_bytes = sp.files["item-1"][-1]
    uploaded = client.post(f"{dbase}/upload", files={"file": ("q.docx", docx_bytes, managed_documents.DOCX_TYPE)}, headers=_auth(owner))
    assert uploaded.status_code == 200
    assert uploaded.json()["document"]["versions"][0]["action"] == "Revised copy uploaded"

    # The Word document (with edits) is now what "Download PDF" serves.
    assert client.get(f"{base}/pdf", headers=_auth(owner)).content == b"%PDF-from-word"


def test_revision_makes_draft_stale(client, db, sp):
    owner = _user(db, "quot_owner2@premnathrail.com")
    inquiry_id, quot = _quotation(client, db, owner)
    base = f"/api/v1/crm/inquiries/{inquiry_id}/quotations/{quot['id']}"
    dbase = f"/api/v1/managed-documents/crm_quotation/{quot['id']}"
    client.post(f"{dbase}", headers=_auth(owner))

    client.patch(base, json={"delivery_time": "12 weeks"}, headers=_auth(owner))
    state = client.get(f"{dbase}", headers=_auth(owner)).json()["document"]
    assert state["is_stale"] is True
    # A stale draft no longer matches the quotation: no edits/uploads, and the PDF falls back to a live render.
    assert client.post(f"{dbase}/edit", headers=_auth(owner)).status_code == 409
    docx = sp.files["item-1"][-1]
    assert client.post(f"{dbase}/upload", files={"file": ("q.docx", docx, managed_documents.DOCX_TYPE)}, headers=_auth(owner)).status_code == 409
    assert client.get(f"{base}/pdf", headers=_auth(owner)).content != b"%PDF-from-word"
    fresh = client.post(f"{dbase}", headers=_auth(owner)).json()["document"]
    assert fresh["is_stale"] is False and fresh["source_revision"] == 1
    assert client.get(f"{base}/pdf", headers=_auth(owner)).content == b"%PDF-from-word"


def test_only_creator_or_admin_can_change_document(client, db, sp):
    owner = _user(db, "quot_owner3@premnathrail.com")
    other = _user(db, "quot_other@premnathrail.com")
    inquiry_id, quot = _quotation(client, db, owner)
    base = f"/api/v1/crm/inquiries/{inquiry_id}/quotations/{quot['id']}"
    dbase = f"/api/v1/managed-documents/crm_quotation/{quot['id']}"
    assert client.post(f"{dbase}", headers=_auth(other)).status_code == 403
    client.post(f"{dbase}", headers=_auth(owner))
    assert client.get(f"{dbase}", headers=_auth(other)).status_code == 200
    assert client.post(f"{dbase}/edit", headers=_auth(other)).status_code == 403


def test_changes_shows_word_edits_and_amount_warning(client, db, sp):
    owner = _user(db, "quot_owner4@premnathrail.com")
    inquiry_id, quot = _quotation(client, db, owner)
    base = f"/api/v1/crm/inquiries/{inquiry_id}/quotations/{quot['id']}"
    dbase = f"/api/v1/managed-documents/crm_quotation/{quot['id']}"
    client.post(f"{dbase}", headers=_auth(owner))
    assert client.get(f"{dbase}/changes", headers=_auth(owner)).json()["changed"] is False

    # Simulate an edit in Word: a price changed in the items table and a note added.
    edited = Document(io.BytesIO(sp.files["item-1"][0]))
    cell = edited.tables[1].rows[1].cells[-1]
    cell.paragraphs[0].runs[0].text = "50,000.00"
    edited.add_paragraph("Special note: free training for 2 operators.")
    buf = io.BytesIO()
    edited.save(buf)
    client.post(f"{dbase}/upload", files={"file": ("q.docx", buf.getvalue(), managed_documents.DOCX_TYPE)}, headers=_auth(owner))

    changes = client.get(f"{dbase}/changes", headers=_auth(owner)).json()
    assert changes["changed"] is True and changes["baseline_version"] == "1.0" and changes["latest_version"] == "2.0"
    assert {"type": "added", "text": "Special note: free training for 2 operators."} in changes["lines"]
    # The old line total still appears in the Grand total row, so only the new amount is "added" — enough to warn.
    assert changes["amounts_added"] == ["50,000.00"]
